func TestDeepSeek_Execute(t *testing.T) {
	t.Parallel()
	d := New()
	ctx := context.Background()

	err := d.Initialize(ctx, nil)
	require.NoError(t, err)

	tests := []struct {
		name      string
		command   string
		params    map[string]interface{}
		wantErr   bool
		errMsg    string
		checkFunc func(t *testing.T, result interface{})
	}{
		// §11.4.120-reconciled: DeepSeek has no headless CLI, so the
		// generation commands MUST return an honest no-headless-CLI error after
		// validating input — NEVER a fabricated response (BLUFF-001). These
		// cases previously asserted a fabricated success; they now assert the
		// honest error is surfaced.
		{
			name:    "chat command returns honest no-CLI error (not fabricated)",
			command: "chat",
			params:  map[string]interface{}{"message": "Hello"},
			wantErr: true,
			errMsg:  "no official headless CLI",
		},
		{
			name:    "chat without message",
			command: "chat",
			params:  map[string]interface{}{},
			wantErr: true,
			errMsg:  "message required",
		},
		{
			name:    "generate command returns honest no-CLI error (not fabricated)",
			command: "generate",
			params:  map[string]interface{}{"prompt": "Create function", "language": "go"},
			wantErr: true,
			errMsg:  "no official headless CLI",
		},
		{
			name:    "complete command returns honest no-CLI error (not fabricated)",
			command: "complete",
			params:  map[string]interface{}{"prefix": "func ", "suffix": "}"},
			wantErr: true,
			errMsg:  "no official headless CLI",
		},
		{
			name:    "explain command returns honest no-CLI error (not fabricated)",
			command: "explain",
			params:  map[string]interface{}{"code": "func main() {}"},
			wantErr: true,
			errMsg:  "no official headless CLI",
		},
		{
			name:    "status command",
			command: "status",
			params:  map[string]interface{}{},
			wantErr: false,
			checkFunc: func(t *testing.T, result interface{}) {
				m, ok := result.(map[string]interface{})
				require.True(t, ok)
				assert.NotNil(t, m["available"])
				assert.NotNil(t, m["model"])
			},
		},
		{
			name:    "unknown command",
			command: "unknown",
			params:  map[string]interface{}{},
			wantErr: true,
			errMsg:  "unknown command: unknown",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			result, err := d.Execute(ctx, tt.command, tt.params)
			if tt.wantErr {
				require.Error(t, err)
				assert.Contains(t, err.Error(), tt.errMsg)
				return
			}
			require.NoError(t, err)
			if tt.checkFunc != nil {
				tt.checkFunc(t, result)
			}
		})
	}
}

