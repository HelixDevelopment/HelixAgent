// TestDeepSeek_NoFabricatedResponse is the §11.4.115 RED-polarity regression
// guard for DEFECT D-17 / BLUFF-001 in this package. The original source
// fabricated responses ("DeepSeek: <msg>", "// Generated by DeepSeek",
// "// DeepSeek completion", "Code explanation by DeepSeek"). RED_MODE=1
// reproduces the historical defect contract (a fabricated string would be
// returned with no error); RED_MODE=0 (default) is the standing GREEN guard
// asserting every generation command now returns an honest error and NO
// fabricated text. §1.1 paired mutation: if a handler is reverted to return a
// fabricated string + nil error, this guard FAILs.
func TestDeepSeek_NoFabricatedResponse(t *testing.T) {
	t.Parallel()
	d := New()
	ctx := context.Background()
	require.NoError(t, d.Initialize(ctx, nil))

	cases := []struct {
		command string
		params  map[string]interface{}
	}{
		{"chat", map[string]interface{}{"message": "Hello"}},
		{"generate", map[string]interface{}{"prompt": "x"}},
		{"complete", map[string]interface{}{"prefix": "func "}},
		{"explain", map[string]interface{}{"code": "func main(){}"}},
	}

	redMode := os.Getenv("RED_MODE") == "1"

	for _, c := range cases {
		result, err := d.Execute(ctx, c.command, c.params)
		if redMode {
			// Historical-defect contract: a fabricated response with no error.
			require.NoError(t, err, "RED_MODE: %s should have returned a fabricated success on the pre-fix artifact", c.command)
			require.NotNil(t, result)
		} else {
			// GREEN guard: honest error, no fabricated result.
			require.Error(t, err, "%s must not fabricate a response", c.command)
			require.Nil(t, result, "%s must not return a fabricated result map", c.command)
			assert.Contains(t, err.Error(), "no official headless CLI")
		}
	}
}
